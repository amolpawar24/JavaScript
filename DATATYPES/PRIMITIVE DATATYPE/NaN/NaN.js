//! NaN
//* NaN Stands for Not a Number.
//* NaN is a Special value in JavaScript that represents the result of an invalid mathematical operation or an undefined numerical result.
//* NaN is Not Seperate DataType, it is a part of Number DataType.
//todo: It appears when a numeric calculation fails or when a non-numeric value is used in a mathematical operation.

//* Example of NaN
console.log(0 / 0); // Output: NaN
console.log(Math.sqrt(-1)); // Output: NaN
console.log(parseInt("Hello")); // Output: NaN 
console.log();
